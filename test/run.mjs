test('allowMacro turns the gate off and the file still gets stamped', async () => {
  const handlers = new Map()
  const ctx = {
    on: (event, handler) => handlers.set(event, handler),
    effect: () => {},
    logger: { info: () => {}, warn: () => {} },
  }
  apply(ctx, { author: '张三', allowMacro: true })
  const allowed = await handlers.get('tools/pre-execute')(
    { arguments: { path: 'a.docm' }, agent: { session: { id: 's3' } } },
    async () => ({ kind: 'allow' }),
  )
  assert.equal(allowed.kind, 'allow')

  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'dsh-stamp-macro-'))
  const file = path.join(dir, 'macro.docm')
  await fs.writeFile(file, DOCX)
  await stampFile(file, { author: '张三' }, {})
  const core = readText(readZip(await fs.readFile(file)), 'docProps/core.xml')
  assert.match(core, /<dc:creator>张三<\/dc:creator>/)
  await fs.rm(dir, { recursive: true, force: true })
})

test('stamps through the post-execute hook', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'dsh-stamp-hook-'))
  const file = path.join(dir, 'out.docx')
  await fs.writeFile(file, DOCX)
  const handlers = new Map()
  const ctx = {
    on: (event, handler) => handlers.set(event, handler),
    effect: () => {},
    logger: { info: () => {}, warn: () => {} },
  }
  apply(ctx, { author: '李四' })
  const post = handlers.get('tools/post-execute')
  const decision = await post(
    { arguments: { path: file }, agent: { session: { id: 's2' } } },
    { content: [] },
    async () => ({ kind: 'accept' }),
  )
  assert.equal(decision.kind, 'accept')
  const core = readText(readZip(await fs.readFile(file)), 'docProps/core.xml')
  assert.match(core, /<dc:creator>李四<\/dc:creator>/)
  await fs.rm(dir, { recursive: true, force: true })
})

test('stamps a file on disk and keeps its mtime', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'dsh-stamp-'))
  const file = path.join(dir, 'report.docx')
  await fs.writeFile(file, DOCX)
  const before = await fs.stat(file)
  const result = await stampFile(file, { author: '张三' }, {})
  assert.equal(result.changed, true)
  const after = await fs.stat(file)
  assert.equal(Math.round(after.mtimeMs), Math.round(before.mtimeMs))
  const core = readText(readZip(await fs.readFile(file)), 'docProps/core.xml')
  assert.match(core, /<dc:creator>张三<\/dc:creator>/)
  await fs.rm(dir, { recursive: true, force: true })
})

for (const [name, body] of queue) {
  try {
    await body()
    passed += 1
    console.log(`  ok  ${name}`)
  } catch (error) {
    failed += 1
    console.log(`FAIL  ${name}`)
    console.log(`      ${error.message}`)
  }
}

console.log(`\n${passed} passed, ${failed} failed`)
process.exit(failed === 0 ? 0 : 1)
