console.log('zip engine')
test('rewrites one entry and keeps the rest byte-identical', () => {
  const before = readZip(DOCX)
  const documentBefore = readEntry(before, 'word/document.xml')
  const result = normalizeBuffer(DOCX, '.docx', META)
  const after = readZip(result.buffer)
  assert.deepEqual(readEntry(after, 'word/document.xml'), documentBefore)
  assert.equal(after.entries.length, before.entries.length - 1, 'custom.xml should be dropped')
})

test('rejects an OLE container instead of guessing', () => {
  const ole = Buffer.from([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1, 0, 0, 0, 0])
  assert.throws(() => normalizeBuffer(ole, '.docx', META), SkipError)
})

console.log('docx')
test('sets author, dates, and drops the generator description', () => {
  const result = normalizeBuffer(DOCX, '.docx', META)
  const zip = readZip(result.buffer)
  const core = readText(zip, 'docProps/core.xml')
  assert.match(core, /<dc:creator>张三<\/dc:creator>/)
  assert.match(core, /<cp:lastModifiedBy>张三<\/cp:lastModifiedBy>/)
  assert.match(core, /2026-10-23T11:00:00Z/)
  assert.doesNotMatch(core, /python-docx/)
  assert.doesNotMatch(core, /<dc:description/)
  assert.match(core, /<dc:title>Weekly Research<\/dc:title>/, 'title must survive')
})

test('is idempotent', () => {
  const once = normalizeBuffer(DOCX, '.docx', META)
  const twice = normalizeBuffer(once.buffer, '.docx', META)
  assert.equal(twice.changed, false)
})

