console.log('rtf')
test('rewrites the info group and encodes CJK', () => {
  const source = '{\\rtf1\\ansi\\deff0{\\fonttbl{\\f0 Arial;}}{\\info{\\title Report}{\\author Old}}{\\pard Hello}}'
  const out = rewriteRtf(source, META)
  assert.match(out, /\\author \\u24352\?\\u19977\?;/)
  assert.match(out, /\\creatim\\yr2026\\mo10\\dy23/)
  assert.match(out, /\\title Report/, 'unrelated info entries survive')
  assert.ok(out.startsWith('{\\rtf1'))
})

test('inserts an info group when the document has none', () => {
  const out = rewriteRtf('{\\rtf1\\ansi Hello}', META)
  assert.match(out, /^\{\\rtf1\{\\info\{\\author /)
})

console.log('pdf')
test('appends an incremental update and leaves the original bytes alone', () => {
  const source = buildPdf()
  const result = normalizeBuffer(source, '.pdf', META)
  assert.ok(result.buffer.subarray(0, source.length).equals(source), 'original bytes must be untouched')
  const text = result.buffer.toString('latin1')
  assert.match(text, /\/Info 4 0 R/)
  assert.match(text, /\/Prev \d+/)
  assert.match(text, /%PDF-1\.4/)
})

test('uses a UTF-16BE hex string for a non-ASCII name', () => {
  const result = normalizeBuffer(buildPdf(), '.pdf', META)
  assert.match(result.buffer.toString('latin1'), /\/Author <FEFF/)
})

