/**
 * OPC adapter: .docx / .xlsx / .pptx / .xlsb.
 *
 * All four are ZIP packages whose core properties live in
 * `docProps/core.xml`. The adapter rewrites that one part, drops custom
 * properties (a second place where generator names accumulate), and leaves
 * every other part untouched.
 */

import { readZip, writeZip, readText, findEntryName, hasEncryptedEntry } from '../zip.js'
import { SkipError } from '../errors.js'
import { escapeXml, stripControls, setElementText, removeElement } from '../xml.js'
import { toW3cdtf } from '../time.js'

export const id = 'opc'
export const extensions = ['.docx', '.xlsx', '.pptx', '.xlsb']

const CORE = 'docProps/core.xml'
const CUSTOM = 'docProps/custom.xml'

// Namespace declarations used only when an element has to be inserted: writers
// such as openpyxl declare `xmlns:dc` on the element itself, not on the root.
const DC = 'xmlns:dc="http://purl.org/dc/elements/1.1/"'
const CP = 'xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"'
const DCTERMS = 'xmlns:dcterms="http://purl.org/dc/terms/"'
const XSI = 'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"'

/** Rewrite core.xml, preserving everything this plugin does not own. */
export function rewriteCore(xml, meta) {
  const author = escapeXml(stripControls(meta.author))
  const created = toW3cdtf(meta.created)
  const modified = toW3cdtf(meta.modified)
  let next = xml

  next = setElementText(next, 'dc:creator', author, 'cp:coreProperties', DC)
  if (next === null) return null
  next = setElementText(next, 'cp:lastModifiedBy', author, 'cp:coreProperties', CP)
  if (next === null) return null
  next = setElementText(
    next,
    'dcterms:created',
    created,
    'cp:coreProperties',
    `xsi:type="dcterms:W3CDTF" ${DCTERMS} ${XSI}`,
  )
  if (next === null) return null
  next = setElementText(
    next,
    'dcterms:modified',
    modified,
    'cp:coreProperties',
    `xsi:type="dcterms:W3CDTF" ${DCTERMS} ${XSI}`,
  )
  if (next === null) return null
  next = setElementText(next, 'cp:revision', '1', 'cp:coreProperties', CP)
  if (next === null) return null
  // "generated by python-docx" lives here; there is no case for keeping it.
  next = removeElement(next, 'dc:description')
  return next
}

function dropCustomPart(zip, replacements, deletions) {
  const customName = findEntryName(zip, CUSTOM)
  if (!customName) return

  deletions.add(customName)

  const relsName = findEntryName(zip, '_rels/.rels')
  const rels = relsName ? readText(zip, relsName) : undefined
  if (rels) {
    const stripped = rels.replace(/<Relationship\b[^>]*custom\.xml[^>]*\/>/gi, '')
    if (stripped !== rels) replacements.set(relsName, Buffer.from(stripped, 'utf8'))
  }

  const typesName = findEntryName(zip, '[Content_Types].xml')
  const types = typesName ? readText(zip, typesName) : undefined
  if (types) {
    const stripped = types.replace(/<Override\b[^>]*custom\.xml[^>]*\/>/gi, '')
    if (stripped !== types) replacements.set(typesName, Buffer.from(stripped, 'utf8'))
  }
}

export function stamp(buffer, meta) {
  const zip = readZip(buffer)
  if (hasEncryptedEntry(zip)) throw new SkipError('文件已加密，无法改写属性')

  const coreName = findEntryName(zip, CORE)
  if (!coreName) throw new SkipError('缺少 docProps/core.xml，可能不是标准 Office 文件')

  const core = readText(zip, coreName)
  const rewritten = rewriteCore(core, meta)
  if (rewritten === null) throw new SkipError('core.xml 结构无法识别')

  const replacements = new Map([[coreName, Buffer.from(rewritten, 'utf8')]])
  const deletions = new Set()
  dropCustomPart(zip, replacements, deletions)

  return { buffer: writeZip(zip, replacements, deletions), format: 'opc' }
}
